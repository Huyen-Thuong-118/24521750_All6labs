// gen_collision.cpp — Wang et al. (2005) MD5 Collision Demonstration
// Hardcodes the 128-byte collision pair from:
//   "How to Break MD5 and Other Hash Functions"
//   Xiaoyun Wang, Hongbo Yu — EUROCRYPT 2005
//
// Both M1 and M2 produce MD5 = 79054025255fb1a26e4bc422aef54eb4
// Differences: 6 bits at byte offsets 0x13, 0x2d, 0x3b, 0x53, 0x6d, 0x7b
//
// Build: add to CMakeLists.txt as target gen_collision
// Usage: ./gen_collision [outdir]   (default outdir = ".")
